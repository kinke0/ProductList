#!/bin/bash
# V1.0.10 修正5.1.3和5.6.2章节图片：从原始正确位置复制图片 + 清理错误目录
# 在服务器上执行: bash V1.0.10_cleanup_5_6_2_images.sh
# 执行顺序: 先执行本shell脚本，再执行SQL脚本

