# ============================================================
# 第二部分：5.1.3 门诊药房管理系统（从5.3.4住院药房系统复制图片）
# ============================================================
echo ""
echo "=== [5.1.3] 创建目标目录 ==="
mkdir -p "${TARGET_51}"

echo ""
echo "=== [5.1.3] 从5.3.4住院药房系统复制图片 ==="

copy_to_51() {
    local src="$1"
    local name="$2"
    if [ -f "$src" ]; then
        cp "$src" "${TARGET_51}/"
        echo "  复制: ${name}"
    else
        echo "  警告(源文件不存在): ${name} ← ${src}"
    fi
}

copy_to_51 "${SRC_534}/药库入库-一般入库.png" "药库入库-一般入库.png"
copy_to_51 "${SRC_534}/药库入库-即入即出.png" "药库入库-即入即出.png"
copy_to_51 "${SRC_534}/药库入库-特殊入库.png" "药库入库-特殊入库.png"
copy_to_51 "${SRC_534}/药库入库-核准入库.png" "药库入库-核准入库.png"
