SRC_534="${BASE_53}/5.3.4 住院药房系统"
SRC_561="${BASE_56}/5.6.1 药库管理系统"

echo "=========================================="
echo "=== V1.0.10 修正5.1.3和5.6.2章节图片 ==="
echo "=========================================="

# ============================================================
# 第一部分：5.6.2 中药房管理系统（从5.6.1药库管理系统复制图片）
# ============================================================
echo ""
echo "=== [5.6.2] 创建目标目录 ==="
