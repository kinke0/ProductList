BASE_51="${DATA_DIR}/3/5. 智慧医疗/5.1 门诊诊疗业务"
BASE_53="${DATA_DIR}/3/5. 智慧医疗/5.3 住院诊疗业务"
BASE_56="${DATA_DIR}/3/5. 智慧医疗/5.6 医疗保障业务"
TARGET_51="${BASE_51}/5.1.3 门诊药房管理系统"
