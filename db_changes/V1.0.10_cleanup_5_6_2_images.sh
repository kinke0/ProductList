copy_to_56 "${SRC_561}/月结-月结记录.png" "月结-月结记录.png"
copy_to_56 "${SRC_561}/月结-月结明细.png" "月结-月结明细.png"

echo ""
echo "=== [5.6.2] 处理门诊直接发药-草药.png ==="
HERB_SRC="${BASE_56}/5.6.2 中药房管理系统---补全完整的中药房管理功能说明/门诊直接发药-草药.png"
if [ -f "$HERB_SRC" ]; then
    cp "$HERB_SRC" "${TARGET_56}/"
    echo "  复制(从wrong_name目录): 门诊直接发药-草药.png"
else
    echo "  警告: 门诊直接发药-草药.png 原文件不存在，尝试从5.1.3复制近似文件"
    if [ -f "${TARGET_51}/门诊直接发药.png" ]; then
        cp "${TARGET_51}/门诊直接发药.png" "${TARGET_56}/门诊直接发药-草药.png"
        echo "  已从5.1.3复制: 门诊直接发药.png → 门诊直接发药-草药.png"
    else
        cp "${BASE_51}/5.1.3 门诊药房管理系统/门诊直接发药.png" "${TARGET_56}/门诊直接发药-草药.png"
        echo "  已从5.1.3复制: 门诊直接发药.png → 门诊直接发药-草药.png"
    fi
