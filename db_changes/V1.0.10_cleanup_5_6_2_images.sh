copy_to_51 "${SRC_534}/月结-月结记录.png" "月结-月结记录.png"
copy_to_51 "${SRC_534}/月结-月结明细.png" "月结-月结明细.png"

# ============================================================
# 第三部分：删除错误物理目录
# ============================================================
echo ""
echo "=== 删除5.6域下的错误物理目录 ==="
WRONG_DIRS_56=(
    "5.6.2 中药房管理系统---补全完整的中药房管理功能说明"
    "5.9.3.1 路径基础维护"
    "5.9.3.2 路径模板维护"
    "5.9.3.3 临床路径执行"
    "5.9.3.4 路径统计分析"
    "5.1.3.3 药房管理"
    "5.3.4.5.1 入库管理"
    "5.3.4.5.2 出库管理"
    "5.3.4.7.1 盘点管理"
    "5.3.4.8.1 月结管理"
)
