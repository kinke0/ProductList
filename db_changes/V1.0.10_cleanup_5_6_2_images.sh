echo ""
echo "=== [5.6.2] 从5.6.1药库管理系统复制图片 ==="

copy_to_56() {
    local src="$1"
    local name="$2"
    if [ -f "$src" ]; then
        cp "$src" "${TARGET_56}/"
        echo "  复制: ${name}"
    else
        echo "  警告(源文件不存在): ${name} ← ${src}"
    fi
}

copy_to_56 "${SRC_561}/药库入库-一般入库.png" "药库入库-一般入库.png"
copy_to_56 "${SRC_561}/药库入库-即入即出.png" "药库入库-即入即出.png"
copy_to_56 "${SRC_561}/药库入库-特殊入库.png" "药库入库-特殊入库.png"
copy_to_56 "${SRC_561}/药库入库-核准入库.png" "药库入库-核准入库.png"
copy_to_56 "${SRC_561}/药库入库-发票补录.png" "药库入库-发票补录.png"
copy_to_56 "${SRC_561}/药库出库-一般出库.png" "药库出库-一般出库.png"
